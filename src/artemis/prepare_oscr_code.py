"""Build a licence-filtered, repository-grouped Python corpus from OSCR.

Only the repository manifests and immutable Parquet blocks selected by the caller
are downloaded. No crawl of GitHub or the entire OSCR archive is performed.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
from collections import Counter
from pathlib import Path
from typing import Any, Callable, Iterable, Mapping

ROWS_PER_GROUP = 64
DEFAULT_ALLOWED_SPDX = frozenset(
    {"0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "CC0-1.0", "ISC", "MIT", "Unlicense"}
)
EXCLUDED_PATH_PARTS = frozenset(
    {"build", "dist", "generated", "node_modules", "third_party", "third-party", "vendor", "__pycache__"}
)
SECRET_PATTERNS = (
    re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9_]{20,}\b"),
    re.compile(r"\bsk-[A-Za-z0-9_-]{24,}\b"),
)
EMAIL_PATTERN = re.compile(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", re.IGNORECASE)


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def repository_split(repository: str, validation_percent: int = 10) -> str:
    """Keep all files from a repository in the same deterministic split."""
    if not 0 <= validation_percent <= 50:
        raise ValueError("validation_percent must be between 0 and 50")
    bucket = int(hashlib.sha256(repository.encode("utf-8")).hexdigest()[:8], 16) % 100
    return "validation" if bucket < validation_percent else "train"


def excluded_path(path: str) -> bool:
    parts = {part.lower() for part in Path(path).parts}
    lowered = path.lower()
    return bool(parts & EXCLUDED_PATH_PARTS) or "generated by" in lowered


def secret_or_contact_pattern(content: str) -> bool:
    if EMAIL_PATTERN.search(content):
        return True
    return any(pattern.search(content) for pattern in SECRET_PATTERNS)


def curate_oscr_files(
    repository_manifests: Iterable[Mapping[str, Any]],
    *,
    read_row: Callable[[str, int], Mapping[str, Any]],
    allowed_spdx: set[str] | frozenset[str] = DEFAULT_ALLOWED_SPDX,
    validation_percent: int = 10,
    min_bytes: int = 128,
    max_bytes: int = 256_000,
    max_files: int | None = None,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, int]]:
    if not allowed_spdx:
        raise ValueError("allowed_spdx must not be empty")
    if not 0 <= validation_percent <= 50:
        raise ValueError("validation_percent must be between 0 and 50")
    if min_bytes < 1 or max_bytes < min_bytes:
        raise ValueError("invalid byte limits")
    if max_files is not None and max_files < 1:
        raise ValueError("max_files must be positive")

    train: list[dict[str, Any]] = []
    validation: list[dict[str, Any]] = []
    counts: Counter[str] = Counter()
    seen_hashes: set[str] = set()

    for repository_manifest in repository_manifests:
        repository = (
            repository_manifest.get("address")
            or repository_manifest.get("repository")
            or repository_manifest.get("url")
        )
        license_id = repository_manifest.get("license") or repository_manifest.get("licence")
        license_confirmation = repository_manifest.get("license_confirmed_by")
        commit = repository_manifest.get("commit")

        if not isinstance(repository, str) or not repository.strip():
            counts["rejected_missing_repository_identity"] += 1
            continue
        if not isinstance(license_id, str) or license_id not in allowed_spdx:
            counts["rejected_license_not_allowlisted"] += 1
            continue
        if not license_confirmation:
            counts["rejected_unconfirmed_license"] += 1
            continue
        files = repository_manifest.get("files")
        if not isinstance(files, list):
            counts["rejected_missing_file_manifest"] += 1
            continue

        split = repository_split(repository, validation_percent)
        for file_record in files:
            if max_files is not None and len(train) + len(validation) >= max_files:
                counts["stopped_at_file_limit"] += 1
                counts["accepted_total"] = len(train) + len(validation)
                return train, validation, dict(counts)

            if not isinstance(file_record, Mapping):
                counts["rejected_malformed_file_record"] += 1
                continue
            if str(file_record.get("language", "")).strip().lower() != "python":
                counts["skipped_non_python"] += 1
                continue

            path = file_record.get("path")
            if not isinstance(path, str) or not path.strip():
                counts["rejected_missing_path"] += 1
                continue
            if not path.lower().endswith((".py", ".pyi")) or excluded_path(path):
                counts["skipped_path_filter"] += 1
                continue

            block = file_record.get("block")
            row_index = file_record.get("row")
            expected_hash = file_record.get("sha256")
            if (
                not isinstance(block, str)
                or not block.strip()
                or not isinstance(row_index, int)
                or row_index < 0
                or not isinstance(expected_hash, str)
            ):
                counts["rejected_incomplete_file_provenance"] += 1
                continue
            block_path = Path(block)
            if block_path.is_absolute() or ".." in block_path.parts:
                counts["rejected_unsafe_block_path"] += 1
                continue

            row = read_row(block, row_index)
            content = row.get("content")
            row_hash = row.get("sha256")
            row_language = str(row.get("language", "")).strip().lower()
            if not isinstance(content, str):
                counts["rejected_missing_content"] += 1
                continue
            actual_hash = sha256_text(content)
            if actual_hash != expected_hash.lower() or (
                isinstance(row_hash, str) and row_hash.lower() != actual_hash
            ):
                counts["rejected_content_hash_mismatch"] += 1
                continue
            if row_language and row_language != "python":
                counts["rejected_language_mismatch"] += 1
                continue

            size_bytes = len(content.encode("utf-8"))
            if size_bytes < min_bytes or size_bytes > max_bytes:
                counts["skipped_size_filter"] += 1
                continue
            if secret_or_contact_pattern(content):
                counts["rejected_secret_or_contact_pattern"] += 1
                continue
            try:
                ast.parse(content, filename=path)
            except (SyntaxError, ValueError):
                counts["skipped_python_parse_failure"] += 1
                continue
            if actual_hash in seen_hashes:
                counts["skipped_duplicate_content"] += 1
                continue

            seen_hashes.add(actual_hash)
            provenance = {
                "repository": repository,
                "repository_commit": commit,
                "license": license_id,
                "license_confirmed_by": license_confirmation,
                "path": path,
                "sha256": actual_hash,
                "language": "Python",
                "lines": int(file_record.get("lines") or content.count("\n") + 1),
                "block": block,
                "row": row_index,
                "split": split,
            }
            example = {"text": content, "provenance": provenance}
            (validation if split == "validation" else train).append(example)
            counts[f"accepted_{split}"] += 1

    counts["accepted_total"] = len(train) + len(validation)
    return train, validation, dict(counts)


def load_oscr_row(block_root: Path, block: str, row_index: int) -> Mapping[str, Any]:
    """Read one row using OSCR's documented 64-row Parquet row groups."""
    try:
        import pyarrow.parquet as pq
    except ImportError as exc:
        raise RuntimeError("Install OSCR data dependencies: pip install -e '.[data]'") from exc

    root = block_root.resolve()
    block_path = (root / block).resolve()
    if root not in block_path.parents:
        raise ValueError(f"block path escapes the configured root: {block}")
    if not block_path.is_file():
        raise FileNotFoundError(f"OSCR Parquet block does not exist: {block_path}")

    parquet_file = pq.ParquetFile(block_path)
    row_group = row_index // ROWS_PER_GROUP
    row_in_group = row_index % ROWS_PER_GROUP
    if row_group >= parquet_file.num_row_groups:
        raise IndexError(f"OSCR row index is outside block: {block} row {row_index}")
    table = parquet_file.read_row_group(row_group, columns=["sha256", "language", "content"])
    if row_in_group >= table.num_rows:
        raise IndexError(f"OSCR row index is outside row group: {block} row {row_index}")
    rows = table.slice(row_in_group, 1).to_pylist()
    if not rows:
        raise IndexError(f"OSCR row was not found: {block} row {row_index}")
    return rows[0]


def load_repository_manifests(
    manifest_dir: Path,
) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    if not manifest_dir.is_dir():
        raise NotADirectoryError(f"manifest directory does not exist: {manifest_dir}")
    paths = sorted(manifest_dir.rglob("*.json"))
    if not paths:
        raise ValueError(f"no repository JSON manifests found under {manifest_dir}")

    manifests: list[dict[str, Any]] = []
    source_records: list[dict[str, str]] = []
    for path in paths:
        raw = path.read_bytes()
        manifest = json.loads(raw.decode("utf-8"))
        if not isinstance(manifest, dict):
            raise ValueError(f"repository manifest must be a JSON object: {path}")
        if manifest.get("format") not in {None, "oscr-script-manifest/1"}:
            raise ValueError(f"unsupported OSCR manifest format: {path}")
        manifests.append(manifest)
        source_records.append(
            {
                "path": path.relative_to(manifest_dir).as_posix(),
                "sha256": hashlib.sha256(raw).hexdigest(),
            }
        )
    return manifests, source_records


def download_selected_oscr_inputs(
    manifest_paths: list[str],
    *,
    revision: str,
    local_dir: Path,
) -> None:
    if not manifest_paths:
        return
    if len(revision) < 7 or revision in {"main", "master", "latest"}:
        raise ValueError("OSCR downloads require an immutable dataset revision")
    try:
        from huggingface_hub import hf_hub_download
    except ImportError as exc:
        raise RuntimeError("Install OSCR data dependencies: pip install -e '.[data]'") from exc

    downloaded_manifests = []
    for manifest_path in manifest_paths:
        if not manifest_path.startswith("manifests/") or ".." in Path(manifest_path).parts:
            raise ValueError(f"not a safe OSCR manifest path: {manifest_path}")
        local_manifest = Path(
            hf_hub_download(
                repo_id="OpenScientificCodeRegistry/Database",
                repo_type="dataset",
                filename=manifest_path,
                revision=revision,
                local_dir=str(local_dir),
            )
        )
        downloaded_manifests.append(local_manifest)

    required_blocks: set[str] = set()
    for manifest_path in downloaded_manifests:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        for entry in manifest.get("files", []):
            block = entry.get("block") if isinstance(entry, dict) else None
            if not isinstance(block, str) or not block.startswith("blocks/"):
                continue
            if ".." in Path(block).parts:
                raise ValueError(f"unsafe OSCR block path in {manifest_path}: {block}")
            required_blocks.add(block)

    for block in sorted(required_blocks):
        hf_hub_download(
            repo_id="OpenScientificCodeRegistry/Database",
            repo_type="dataset",
            filename=block,
            revision=revision,
            local_dir=str(local_dir),
        )


def write_corpus(
    output_dir: Path,
    train: list[dict[str, Any]],
    validation: list[dict[str, Any]],
    counts: Mapping[str, int],
    *,
    dataset_revision: str,
    allowed_spdx: set[str] | frozenset[str],
    source_manifests: list[dict[str, str]],
) -> dict[str, Any]:
    output_dir.mkdir(parents=True, exist_ok=True)

    def write_split(path: Path, text_path: Path, examples: list[dict[str, Any]]) -> None:
        with path.open("w", encoding="utf-8") as jsonl_stream, text_path.open(
            "w", encoding="utf-8"
        ) as text_stream:
            for example in examples:
                jsonl_stream.write(
                    json.dumps(example, ensure_ascii=False, sort_keys=True) + "\n"
                )
                text_stream.write(example["text"].rstrip() + "\n\n")

    write_split(output_dir / "train.jsonl", output_dir / "train.txt", train)
    write_split(
        output_dir / "validation.jsonl",
        output_dir / "validation.txt",
        validation,
    )
    manifest = {
        "dataset": "OpenScientificCodeRegistry/Database",
        "dataset_revision": dataset_revision,
        "license_policy": {
            "allowed_spdx_exact_matches": sorted(allowed_spdx),
            "requires_license_confirmed_by": True,
            "note": (
                "OSCR scripts retain their source repository licence. This allowlist "
                "is a project filter, not a legal determination or a dataset-wide licence."
            ),
        },
        "source_manifests": source_manifests,
        "counts": dict(counts),
        "train_files": len(train),
        "validation_files": len(validation),
        "files": {
            "train_jsonl": "train.jsonl",
            "validation_jsonl": "validation.jsonl",
            "train_text_for_tokenizer": "train.txt",
            "validation_text_for_inspection": "validation.txt",
        },
        "limitations": [
            "Only the selected repository manifests and referenced blocks were considered.",
            "Exact SPDX matching rejects unknown and compound licence expressions.",
            "The built-in secret/contact scan is not a comprehensive security or PII audit.",
            "Repository-level splits reduce same-repository leakage but do not prove benchmark non-contamination.",
        ],
    }
    (output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return manifest


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest-dir", type=Path, default=Path("data/oscr"))
    parser.add_argument("--blocks-dir", type=Path, default=Path("data/oscr"))
    parser.add_argument("--hub-manifest-path", action="append", default=[])
    parser.add_argument("--dataset-revision", default="b0e3fadb276678880f7f3d764308fbebd3bcd044")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--allow-spdx", action="append", dest="allowed_spdx")
    parser.add_argument("--validation-percent", type=int, default=10)
    parser.add_argument("--min-bytes", type=int, default=128)
    parser.add_argument("--max-bytes", type=int, default=256_000)
    parser.add_argument("--max-files", type=int, default=10_000)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    allowed = set(args.allowed_spdx or DEFAULT_ALLOWED_SPDX)
    if args.hub_manifest_path:
        download_selected_oscr_inputs(
            args.hub_manifest_path,
            revision=args.dataset_revision,
            local_dir=args.manifest_dir,
        )
    manifests, source_records = load_repository_manifests(args.manifest_dir)
    train, validation, counts = curate_oscr_files(
        manifests,
        read_row=lambda block, row: load_oscr_row(args.blocks_dir, block, row),
        allowed_spdx=allowed,
        validation_percent=args.validation_percent,
        min_bytes=args.min_bytes,
        max_bytes=args.max_bytes,
        max_files=args.max_files,
    )
    summary = write_corpus(
        args.output_dir,
        train,
        validation,
        counts,
        dataset_revision=args.dataset_revision,
        allowed_spdx=allowed,
        source_manifests=source_records,
    )
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
